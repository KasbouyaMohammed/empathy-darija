"""Qualitative examples for the error analysis, selected by fixed rules (no hand-picking), and the
per-system x policy summary table. Only benchmark messages (our CFPB-derived or translated texts) are shown;
human-written DarijaBanking messages are never reproduced.

    python scripts/17_examples.py
Outputs: paper/tables/tab_examples.tex, paper/tables/tab_system_policy.tex, paper/tables/appendix_prompts.tex
"""
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
A = ROOT / "results/analysis"
OUT = ROOT / "paper/tables"
SEED = 3
SYS = {"claude-sonnet-5-5": "Claude Sonnet 5.5", "claude-haiku-5-5": "Claude Haiku 5.5", "atlas9b": "Atlas-Chat-9B",
       "qwen3_8b": "Qwen3-8B", "llama31_8b": "Llama-3.1-8B", "gemma2_9b": "Gemma-2-9B", "atlas2b": "Atlas-Chat-2B"}


def tex(s, n=330):
    s = " ".join(str(s).split())
    s = s if len(s) <= n else s[:n].rsplit(" ", 1)[0] + " [\\ldots]"
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"),
                 ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}"),
                 ("\\textbackslash\\{\\}", r"\textbackslash{}")):
        s = s.replace(a, b)
    return s.replace("**", "")


def load():
    import glob
    fs = [ROOT / "data/processed/responses_claude.csv"] + [Path(f) for f in sorted(glob.glob(str(ROOT / "data/processed/responses_open_*.csv")))
                                                          if "pilot" not in f and "smoke" not in f]
    d = pd.concat([pd.read_csv(f) for f in fs], ignore_index=True)
    obj = pd.read_csv(A / "replies_objective.csv")[["item_key", "reply_lid"]]
    d["item_key"] = d.item_id + "|" + d.system + "|" + d.policy
    return d.merge(obj, on="item_key", how="left")


def examples():
    d = load()
    b = d[d.set == "benchmark"]
    rows = []
    # 1. Policies on an English fraud complaint (Sonnet), same scenario for P0/P1/P2.
    fraud = b[(b.system == "claude-sonnet-5-5") & (b.variety == "en") & (b.category == "fraud_unauthorized")]
    sid = sorted(fraud.scenario_id.unique())[0]
    g = fraud[fraud.scenario_id == sid].set_index("policy")
    rows.append(("Policies, fraud complaint (EN, Sonnet)", "Customer", g.iloc[0].message))
    for p in ("P0", "P1", "P2"):
        rows.append(("", p, g.loc[p, "reply"]))
    # 2. Over-empathy of P1 on an information request (EN, Haiku), first informational scenario.
    info = b[(b.system == "claude-haiku-5-5") & (b.variety == "en") & b.category.str.startswith("info")]
    sid = sorted(info.scenario_id.unique())[0]
    g = info[info.scenario_id == sid].set_index("policy")
    rows.append(("Information request (EN, Haiku)", "Customer", g.iloc[0].message))
    for p in ("P1", "P2"):
        rows.append(("", p, g.loc[p, "reply"]))
    # 3. Script switching: Atlas-Chat-9B answering an Arabizi message in Arabic script (shown by its identified variety).
    at = b[(b.system == "atlas9b") & (b.variety == "ary_latn") & (b.policy == "P2") & (b.reply_lid == "ary")]
    r = at.sample(1, random_state=SEED).iloc[0]
    rows.append(("Script switching (Arabizi, Atlas-Chat-9B, P2)", "Customer", r.message))
    rows.append(("", "Reply", "[Arabic-script Darija reply, identified as ary; not typeset]"))
    # 4. Degenerate repetition: Qwen3-8B on Arabizi, still truncated after regeneration.
    q = b[(b.system == "qwen3_8b") & (b.variety == "ary_latn") & (b.stop_reason == "max_tokens")]
    if len(q):
        r = q.sample(1, random_state=SEED).iloc[0]
        rows.append(("Repetition loop (Arabizi, Qwen3-8B, excluded)", "Customer", r.message))
        rows.append(("", "Reply", r.reply))
    # 5. Faithful Arabizi reply (LoRA, no prompt), same Arabizi scenario as example 3.
    lo = b[(b.system == "lora2b_frac100_seed0") & (b.item_id == at.sample(1, random_state=SEED).iloc[0].item_id)]
    if len(lo):
        rows.append(("Same message, distilled model (no prompt)", "Reply", lo.iloc[0].reply))
    lines = [r"\begin{tabular}{|p{1.9cm}|p{0.9cm}|p{14.0cm}|}", r"\hline",
             r"\textbf{Case} & \textbf{Turn} & \textbf{Text (truncated at 330 characters)} \\", r"\hline"]
    for case, turn, text in rows:
        if case and len(lines) > 4:
            lines.append(r"\hline")
        lines.append(f"{tex(case, 200)} & {turn} & {tex(text)} \\\\")
    lines += [r"\hline", r"\end{tabular}"]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "tab_examples.tex").write_text("% Generated by scripts/17_examples.py -- do not edit by hand.\n" + "\n".join(lines) + "\n")


def system_policy():
    l = pd.read_csv(A / "replies_long.csv")
    l = l[(l.set == "benchmark") & l.policy.isin(["P0", "P1", "P2"])]
    per = l.groupby(["item_key", "system", "policy"]).agg(
        empathy=("empathy", "median"), helpfulness=("helpfulness", "median"), action=("action_cov", "median"),
        appropriate=("approp", lambda x: float(np.median(x) == 0)), fidelity=("fidelity", "first"),
        words=("words", "first")).reset_index()
    t = per.groupby(["system", "policy"]).mean(numeric_only=True)
    lines = [r"\begin{tabular}{|l|c|r|r|r|r|r|r|}", r"\hline",
             r"\textbf{System} & \textbf{Pol.} & \textbf{Fid.} & \textbf{Emp.} & \textbf{Appr.} & \textbf{Help.} & \textbf{Act.} & \textbf{Words} \\",
             r"\hline"]
    for s in SYS:
        if s not in t.index.get_level_values(0):
            continue
        for k, p in enumerate([p for p in ("P0", "P1", "P2") if (s, p) in t.index]):
            r = t.loc[(s, p)]
            lines.append((SYS[s] if k == 0 else "") + f" & {p} & {100 * r.fidelity:.0f} & {r.empathy:.2f} & "
                         f"{100 * r.appropriate:.0f} & {r.helpfulness:.2f} & {r.action:.2f} & {r.words:.0f} \\\\")
        lines.append(r"\hline")
    lines.append(r"\end{tabular}")
    (OUT / "tab_system_policy.tex").write_text("% Generated by scripts/17_examples.py -- do not edit by hand.\n" + "\n".join(lines) + "\n")


def appendix_prompts():
    """The frozen prompts, verbatim from scripts/prompts.py, for the appendix."""
    import sys
    sys.path.insert(0, str(ROOT / "scripts"))
    import prompts as P
    def block(title, text):
        paras = [tex(x, 10**6) for x in str(text).split("\n") if x.strip()]
        return rf"\par\noindent\textbf{{{title}}}\par\noindent{{\scriptsize\ttfamily\raggedright " + r"\\ ".join(paras) + r"\par}\medskip"
    parts = [block("Bank context (shared by P0, P1, P2)", P.BANK_CONTEXT)]
    for k in ("P0", "P1", "P2"):
        parts.append(block(f"Style instruction appended for {k}", P.POLICIES[k][len(P.BANK_CONTEXT):]))
    parts.append(block("Judge rubric (benchmark replies)", P.JUDGE_RUBRIC))
    parts.append(block("Judge prompt (EPITOME validation)", P.EPITOME_JUDGE))
    checks = "\n".join(f"{c}: " + "; ".join(v) for c, v in P.CHECKLISTS.items())
    parts.append(block("Required actions per category", checks))
    (OUT / "appendix_prompts.tex").write_text("% Generated by scripts/17_examples.py -- do not edit by hand.\n" + "\n".join(parts) + "\n")


if __name__ == "__main__":
    examples()
    system_policy()
    appendix_prompts()
    print("tables ->", OUT)
