def tex_fidelity():
    """Heat map: share of replies in the customer's variety (prompted benchmark replies, all policies), plus
    the human-written Darija messages and the LoRA model (3 seeds, no prompt)."""
    d = pd.read_csv(ANALYSIS / "replies_objective.csv")
    d["system"] = d.system.where(~d.system.str.startswith("lora2b_frac100"), "lora")
    labels = SYSTEM_LABELS | {"lora": "Atlas-2B + LoRA"}
    systems = [k for k in labels if k in set(d.system)]
    cols = ["en", "fr", "msa", "ary", "ary_latn", "natural"]
    tab = {}
    for sy in systems:
        g = d[(d.system == sy) & (d.policy.isin(["P0", "P1", "P2"]) | (sy == "lora"))]
        for v in cols[:-1]:
            x = g[(g.set == "benchmark") & (g.variety == v)]
            if len(x):
                tab[(sy, v)] = 100 * x.fidelity.mean()
        x = g[g.set == "natural"]
        if len(x):
            tab[(sy, "natural")] = 100 * x.fidelity.mean()
    cw, ch = 1.12, 0.46
    lines = ["% Generated by scripts/make_tex_figures.py -- do not edit by hand.", COLORS,
             r"\begin{tikzpicture}[font=\normalfont\fontfamily{phv}\selectfont\scriptsize]"]
    for i, sy in enumerate(systems):
        y = -i * ch - (0.12 if sy == "lora" else 0)
        lines.append(rf"\node[anchor=east] at (-0.08,{y:.2f}) {{{labels[sy]}}};")
        for j, v in enumerate(cols):
            val = tab.get((sy, v))
            if val is None:
                continue
            x0 = j * cw + (0.12 if v == "natural" else 0)
            txt = "white" if val >= 60 else "black"
            lines.append(rf"\fill[tabblue!{int(round(val))}, draw=white, line width=0.8pt] ({x0:.2f},{y - ch / 2:.2f}) rectangle ({x0 + cw:.2f},{y + ch / 2:.2f});")
            lines.append(rf"\node[text={txt}] at ({x0 + cw / 2:.2f},{y:.2f}) {{{val:.0f}}};")
    for j, v in enumerate(cols):
        x0 = j * cw + (0.12 if v == "natural" else 0)
        name = "Natural" if v == "natural" else VARIETY_LABELS[v]
        lines.append(rf"\node[anchor=south] at ({x0 + cw / 2:.2f},{ch / 2:.2f}) {{{name}}};")
    lines.append(r"\end{tikzpicture}")
    (OUT / "fig_fidelity.tex").write_text("\n".join(lines) + "\n")


def tex_approp():
    """Stacked bars: jury appropriateness shares per policy within each urgency level (benchmark)."""
    d = pd.read_csv(ANALYSIS / "replies_long.csv")
    d = d[(d.set == "benchmark") & d.policy.isin(["P0", "P1", "P2"]) & d.appropriateness.notna()]
    cats = [("too_little", "Too little", "tabblue"), ("appropriate", "Appropriate", "tabgreen"),
            ("excessive", "Excessive", "taborange")]
    unit, bar_h, pitch = 0.055, 0.36, 0.46
    lines = ["% Generated by scripts/make_tex_figures.py -- do not edit by hand.", COLORS,
             r"\begin{tikzpicture}[font=\normalfont\fontfamily{phv}\selectfont\scriptsize]"]
    y = 0.0
    for urg in ["high", "medium", "low"]:
        lines.append(rf"\node[anchor=west, font=\scriptsize\bfseries] at (-1.5,{y + 0.05:.2f}) {{{urg.capitalize()} urgency}};")
        y -= pitch
        for pol in ["P0", "P1", "P2"]:
            g = d[(d.urgency == urg) & (d.policy == pol)]
            if not len(g):
                continue
            share = g.appropriateness.value_counts(normalize=True) * 100
            left = 0.0
            for key, _, col in cats:
                w = share.get(key, 0.0)
                if w > 0:
                    lines.append(rf"\fill[{col}, draw=white, line width=0.3pt] ({left * unit:.3f},{y - bar_h / 2:.3f}) rectangle ({(left + w) * unit:.3f},{y + bar_h / 2:.3f});")
                    if w >= 7:
                        lines.append(rf"\node[text=white, font=\tiny] at ({(left + w / 2) * unit:.3f},{y:.3f}) {{{w:.0f}}};")
                left += w
            lines.append(rf"\node[anchor=east] at (-0.08,{y:.3f}) {{{pol}}};")
            y -= pitch
        y -= 0.12
    for t in range(0, 101, 25):
        lines.append(rf"\node[anchor=north] at ({t * unit:.2f},{y + 0.15:.2f}) {{{t}}};")
    lines.append(rf"\node[anchor=north] at ({50 * unit:.2f},{y - 0.15:.2f}) {{Share of judgments (\%)}};")
    lines += legend([(name, col) for _, name, col in cats], -0.4, y - 0.75, 2.0)
    lines.append(r"\end{tikzpicture}")
    (OUT / "fig_approp.tex").write_text("\n".join(lines) + "\n")


def tex_rq3():
    """Grouped bars with 95% CIs: Spearman rho between judge and human total empathy, per variety."""
    r = pd.read_csv(ANALYSIS / "rq3_agreement.csv")
    r = r[(r.subset == "all") & (r.dimension == "total")]
    judges = [k for k in JUDGE_LABELS if k in set(r.judge)]
    cols = ["tabblue", "taborange", "tabgreen", "tabred", "tabpurple"][:len(judges)]
    varieties = ["en", "fr", "msa", "ary", "ary_latn"]
    vals = {(v, j): row.estimate * 100 for row in r.itertuples() for v, j in [(row.variety, row.judge)]}
    bw = 0.8 / max(1, len(judges))
    lines = ["% Generated by scripts/make_tex_figures.py -- do not edit by hand.", COLORS,
             r"\begin{tikzpicture}[font=\normalfont\fontfamily{phv}\selectfont\scriptsize]"]
    lines += grouped_bars(varieties, judges, vals, cols, ymax=100, height=3.0, group_w=1.45, bar_w=bw * 1.45,
                          ylabel="Spearman $\\rho$ $\\times$ 100", labels=False)
    yscale = 3.0 / 100
    for i, v in enumerate(varieties):
        center = (i + 0.5) * 1.45
        start = center - len(judges) * bw * 1.45 / 2
        for jdx, jn in enumerate(judges):
            row = r[(r.variety == v) & (r.judge == jn)]
            if len(row):
                x = start + (jdx + 0.46) * bw * 1.45
                lo, hi = row.ci_low.iloc[0] * 100 * yscale, row.ci_high.iloc[0] * 100 * yscale
