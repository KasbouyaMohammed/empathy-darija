def tex_cfpb_emotion():
    df = pd.read_parquet(ROOT / "data/processed/cfpb_candidates.parquet")
    groups = {"anger": "Anger", "disgust": "Anger", "fear": "Anxiety", "sadness": "Distress",
              "neutral": "Neutral", "joy": "Other", "surprise": "Other"}
    df["group"] = df["emotion_auto"].map(groups)
    order = ["Anger", "Anxiety", "Distress", "Neutral", "Other"]
    colors = ["tabred", "taborange", "tabblue", "tabgreen", "tabgray"]
    tab = pd.crosstab(df["category"], df["group"])[order]
    share = tab.div(tab.sum(axis=1), axis=0) * 100
    cats = sorted(share.index, key=lambda c: (URGENCY[c] != "high", -tab.loc[c].sum()))

    unit, bar_h, gap = 0.05, 0.42, 0.62   # cm per percentage point; bar height; row pitch
    lines = [
        "% Generated by scripts/make_tex_figures.py -- do not edit by hand.",
        COLORS,
        r"\begin{tikzpicture}[font=\normalfont\fontfamily{phv}\selectfont\scriptsize]",
    ]
    n = len(cats)
    top = (n - 1) * gap
    for t in range(0, 101, 20):
        x = t * unit
        lines.append(rf"\draw[black!15] ({x:.2f},-0.35) -- ({x:.2f},{top + 0.35:.2f});")
        lines.append(rf"\node[anchor=north] at ({x:.2f},-0.38) {{{t}}};")
    lines.append(rf"\node[anchor=north] at ({50 * unit:.2f},-0.72) {{Share of complaints (\%)}};")
    for i, c in enumerate(cats):
        y = top - i * gap
        left = 0.0
        for g, col in zip(order, colors):
            w = share.loc[c, g]
            if w > 0:
                lines.append(rf"\fill[{col}, draw=white, line width=0.3pt] ({left * unit:.3f},{y - bar_h / 2:.3f}) "
                             rf"rectangle ({(left + w) * unit:.3f},{y + bar_h / 2:.3f});")
            left += w
        label = f"{CATEGORY_LABELS[c]} ($n$={int(tab.loc[c].sum())})"
        lines.append(rf"\node[anchor=east] at (-0.08,{y:.3f}) {{{label}}};")
    lines.append(rf"\draw[black!70] (0,-0.35) -- (0,{top + 0.35:.2f});")
    x = -1.6
    for g, col in zip(order, colors):
        lines.append(rf"\fill[{col}] ({x:.2f},-1.42) rectangle ({x + 0.22:.2f},-1.2);")
        lines.append(rf"\node[anchor=west] at ({x + 0.25:.2f},-1.31) {{{g}}};")
        x += 1.45
    lines.append(r"\end{tikzpicture}")
    (OUT / "fig_cfpb_emotion.tex").write_text("\n".join(lines) + "\n")


VARIETY_LABELS = {"en": "EN", "fr": "FR", "msa": "MSA", "ary": "Darija", "ary_latn": "Arabizi", "all": "All"}


def grouped_bars(groups, series, values, colors, ymax=100, height=3.2, group_w=1.25, bar_w=0.3,
                 ylabel="", ytick=20, labels=True, x0=0.0):
    """TikZ lines for a grouped bar chart; values[(group, series)] in data units, y axis from 0 to ymax."""
    yscale = height / ymax
    width = x0 + len(groups) * group_w
    lines = []
    for t in range(0, ymax + 1, ytick):
        y = t * yscale
        lines.append(rf"\draw[black!15] ({x0:.2f},{y:.3f}) -- ({width:.2f},{y:.3f});")
        lines.append(rf"\node[anchor=east] at ({x0 - 0.05:.2f},{y:.3f}) {{{t}}};")
    lines.append(rf"\draw[black!70] ({x0:.2f},0) -- ({width:.2f},0);")
    if ylabel:
        lines.append(rf"\node[rotate=90, anchor=south] at ({x0 - 0.55:.2f},{height / 2:.2f}) {{{ylabel}}};")
    for i, g in enumerate(groups):
        center = x0 + (i + 0.5) * group_w
        start = center - len(series) * bar_w / 2
        for j, (sname, col) in enumerate(zip(series, colors)):
            v = values.get((g, sname))
            if v is None:
                continue
            xl = start + j * bar_w
            lines.append(rf"\fill[{col}] ({xl:.3f},0) rectangle ({xl + bar_w * 0.92:.3f},{v * yscale:.3f});")
            if labels:
                lines.append(rf"\node[anchor=south, font=\tiny, inner sep=1pt] at ({xl + bar_w * 0.46:.3f},"
                             rf"{v * yscale:.3f}) {{{v:.0f}}};")
        lines.append(rf"\node[anchor=north] at ({center:.2f},-0.05) {{{VARIETY_LABELS.get(g, g)}}};")
    return lines


def legend(items, x, y, step=2.3):
    lines = []
    for name, col in items:
        lines.append(rf"\fill[{col}] ({x:.2f},{y - 0.11:.2f}) rectangle ({x + 0.22:.2f},{y + 0.11:.2f});")
        lines.append(rf"\node[anchor=west] at ({x + 0.25:.2f},{y:.2f}) {{{name}}};")
        x += step
    return lines


