def tab_rq4():
    runs = pd.read_csv(A / "rq4_runs.csv").set_index("system")
    long = pd.read_csv(A / "replies_long.csv")
    obj = pd.read_csv(A / "replies_objective.csv")
    dar = lambda x: x[(x.set == "benchmark") & x.variety.isin(["ary", "ary_latn"])]

    def arm_stats(mask_long, mask_obj, judges=None):
        l = dar(long[mask_long(long)])
        if judges is not None:
            l = l[l.judge.isin(judges)]
        o = dar(obj[mask_obj(obj)])
        per = l.groupby("item_key").agg(empathy=("empathy", "median"), helpfulness=("helpfulness", "median"),
                                        appropriate=("approp", lambda x: float(np.median(x) == 0)))
        return {"fidelity": o.fidelity.mean(), **per.mean().to_dict()}

    arms = {
        "Atlas-Chat-2B + P2 prompt": (lambda x: (x.system == "atlas2b") & (x.policy == "P2"),) * 2,
        "Claude Sonnet 5.5 + P2 prompt": (lambda x: (x.system == "claude-sonnet-5-5") & (x.policy == "P2"),) * 2,
    }
    lines = [r"\begin{tabular}{|l|c|c|c|c|}", r"\hline",
             r"\textbf{System (Darija messages)} & \textbf{Fidelity} & \textbf{Empathy} & \textbf{Approp.} & \textbf{Helpful.} \\",
             r"\hline"]
    for name, (ml, mo) in arms.items():
        s = arm_stats(ml, mo)
        lines.append(f"{name} & {100 * s['fidelity']:.0f}\\% & {s['empathy']:.2f} & {100 * s['appropriate']:.0f}\\% & "
                     f"{s['helpfulness']:.2f} \\\\")
    seeds = [f"lora2b_frac100_seed{i}" for i in range(3)]
    st = [arm_stats(lambda x, s=s: x.system == s, lambda x, s=s: x.system == s) for s in seeds]
    m = {k: np.mean([x[k] for x in st]) for k in st[0]}
    sd = {k: np.std([x[k] for x in st], ddof=1) for k in st[0]}
    lines.append(r"\hline" + "\n" + rf"LoRA, no prompt (mean $\pm$ SD, 3 seeds) & {100 * m['fidelity']:.0f}$\pm${100 * sd['fidelity']:.0f}\% & "
                 rf"{m['empathy']:.2f}$\pm${sd['empathy']:.2f} & {100 * m['appropriate']:.0f}$\pm${100 * sd['appropriate']:.0f}\% & "
                 rf"{m['helpfulness']:.2f}$\pm${sd['helpfulness']:.2f} \\")
    for frac in (50, 25):
        s = arm_stats(lambda x, f=frac: x.system == f"lora2b_frac{f}_seed0", lambda x, f=frac: x.system == f"lora2b_frac{f}_seed0")
        lines.append(f"LoRA, {frac}\\% of training data & {100 * s['fidelity']:.0f}\\% & {s['empathy']:.2f} & "
                     f"{100 * s['appropriate']:.0f}\\% & {s['helpfulness']:.2f} \\\\")
    # Non-Claude judges only, to check that the result is not a Claude-judge preference for distilled replies.
    lines.append(r"\hline" + "\n" + r"\multicolumn{5}{|l|}{\textit{Judged by non-Claude judges only}} \\ \hline")
    open_j = [j for j in ["qwen3_8b", "llama31_8b", "gemma2_9b"] if j in set(long.judge)]
    for name, (ml, mo) in list(arms.items()) + [("LoRA, no prompt (seed 0)", (lambda x: x.system == "lora2b_frac100_seed0",) * 2)]:
        s = arm_stats(ml, mo, open_j)
        lines.append(f"{name} & -- & {s['empathy']:.2f} & {100 * s['appropriate']:.0f}\\% & {s['helpfulness']:.2f} \\\\")
    lines += [r"\hline", r"\end{tabular}"]
    write("tab_rq4", "\n".join(lines) + "\n")


