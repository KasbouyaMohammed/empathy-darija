def tab_systems():
    """Replies per system: valid (judged) and excluded (still truncated after the regeneration rule)."""
    import glob
    fs = [ROOT / "data/processed/responses_claude.csv"] + [Path(f) for f in sorted(glob.glob(str(ROOT / "data/processed/responses_open_*.csv")))
                                                          if "pilot" not in f and "smoke" not in f]
    d = pd.concat([pd.read_csv(f) for f in fs], ignore_index=True)
    d["excluded"] = d.get("excluded", 0)
    d["excluded"] = (d.excluded.fillna(0).astype(int) | d.reply.isna() | (d.reply.astype(str).str.strip() == "")).astype(int)
    d["sys"] = d.system.where(~d.system.str.startswith("lora2b_frac100"), "lora100")
    access = {"claude-sonnet-5-5": "API, batch", "claude-haiku-5-5": "API, batch", "atlas9b": "Local, fp32",
              "qwen3_8b": "Local, fp16", "llama31_8b": "Local, fp16", "gemma2_9b": "Local, fp32",
              "atlas2b": "Local, fp32", "lora100": "Local, fp32", "lora2b_frac50_seed0": "Local, fp32",
              "lora2b_frac25_seed0": "Local, fp32"}
    label = SYS | {"lora100": "Atlas-Chat-2B + LoRA (3 seeds)", "lora2b_frac50_seed0": "\\quad LoRA, 50\\% data",
                   "lora2b_frac25_seed0": "\\quad LoRA, 25\\% data"}
    lines = [r"\begin{tabular}{|l|l|c|r|r|}", r"\hline",
             r"\textbf{System} & \textbf{Run} & \textbf{Policies} & \textbf{Replies} & \textbf{Excl.} \\", r"\hline"]
    for k in access:
        g = d[d.sys == k]
        if not len(g):
            continue
        pols = ", ".join(sorted(set(g.policy))) if set(g.policy) != {"none"} else "none"
        lines.append(f"{label[k]} & {access[k]} & {pols} & {len(g) - g.excluded.sum():,} & {g.excluded.sum():,} \\\\")
    lines += [r"\hline", rf"\textbf{{Total}} & & & \textbf{{{len(d) - d.excluded.sum():,}}} & \textbf{{{d.excluded.sum():,}}} \\",
              r"\hline", r"\end{tabular}"]
    write("tab_systems", "\n".join(lines) + "\n")


