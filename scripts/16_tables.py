HEADER = "% Generated by scripts/16_tables.py from results/analysis -- do not edit by hand.\n"


def write(name, body):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{name}.tex").write_text(HEADER + body)


def fmt_p(p):
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def tab_rq3():
    r = pd.read_csv(A / "rq3_agreement.csv")
    r = r[r.subset == "all"]
    dr = pd.read_csv(A / "rq3_drop_vs_en.csv")
    dr = dr[dr.subset == "all"].set_index(["judge", "variety"])
    judges = [j for j in JUDGE if j in set(r.judge)]
    lines = [r"\begin{tabular}{|l|c|c|c|c|c|}", r"\hline",
             r"\textbf{Judge} & " + " & ".join(rf"\textbf{{{VAR_TEX[v]}}}" for v in VAR) + r" \\", r"\hline"]
    for j in judges:
        cells = []
        for v in VAR:
            row = r[(r.judge == j) & (r.variety == v) & (r.dimension == "total")]
            if not len(row):
                cells.append("--")
                continue
            est, lo, hi = row.estimate.iloc[0], row.ci_low.iloc[0], row.ci_high.iloc[0]
            mark = ""
            if v != "en" and (j, v) in dr.index and dr.loc[(j, v), "p_holm"] < 0.05:
                mark = r"$^{*}$"
            cells.append(f"{est:.2f}{mark} [{lo:.2f}, {hi:.2f}]")
        lines.append(f"{JUDGE[j]} & " + " & ".join(cells) + r" \\")
    lines += [r"\hline", r"\end{tabular}"]
    write("tab_rq3", "\n".join(lines) + "\n")

    # Per mechanism QWK, en vs Darija varieties.
    lines = [r"\begin{tabular}{|l|l|c|c|c|c|c|}", r"\hline",
             r"\textbf{Judge} & \textbf{Mech.} & " + " & ".join(rf"\textbf{{{VAR_TEX[v]}}}" for v in VAR) + r" \\",
             r"\hline"]
    for j in judges:
        for k, d in enumerate(["er", "ip", "ex"]):
            cells = []
            for v in VAR:
                row = r[(r.judge == j) & (r.variety == v) & (r.dimension == d)]
                cells.append(f"{row.estimate.iloc[0]:.2f}" if len(row) else "--")
            lines.append((JUDGE[j] if k == 0 else "") + f" & {d.upper()} & " + " & ".join(cells) + r" \\")
        lines.append(r"\hline")
    lines += [r"\end{tabular}"]
    write("tab_rq3_qwk", "\n".join(lines) + "\n")


