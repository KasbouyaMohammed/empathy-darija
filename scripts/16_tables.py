def numbers():
    """paper/tables/numbers.tex: one macro per number quoted in the text, so prose and tables cannot diverge.
    p-value macros (names ending in P) hold the relation too ("<0.001" or "=0.019") and are used in math mode
    after p, e.g. $p\\rqTwoApprPtwoPzeroP$."""
    defs = {}
    fmt_p = lambda p: "<0.001" if p < 0.001 else f"={p:.3f}"

    def put(name, value, fmt="{:.2f}"):
        defs[name] = fmt.format(value) if isinstance(value, (float, np.floating, int, np.integer)) else str(value)

    con = pd.read_csv(A / "rq1_rq2_contrasts.csv")
    def c(rq, outcome, contrast, extra=None):
        g = con[(con.rq == rq) & (con.outcome == outcome) & (con.contrast == contrast)]
        if extra:
            for k, v in extra.items():
                g = g[g[k] == v]
        return g.iloc[0]
    tag = {"ary - en": "AryEn", "ary - fr": "AryFr", "ary - msa": "AryMsa", "ary_latn - en": "LatnEn",
           "ary_latn - fr": "LatnFr", "ary_latn - msa": "LatnMsa", "P2 - P0": "PtwoPzero", "P2 - P1": "PtwoPone"}
    for o, short in (("empathy", "Emp"), ("helpfulness", "Help"), ("action_cov", "Act"), ("fidelity", "Fid")):
        for ct, t in list(tag.items())[:6]:
            row = c("RQ1", o, ct)
            scale = 100 if o == "fidelity" else 1
            fmt = "{:.0f}" if o == "fidelity" else ("{:.3f}" if o == "action_cov" else "{:.2f}")
            put(f"rqOne{short}{t}", row.estimate * scale, fmt)
            put(f"rqOne{short}{t}Lo", row["asymp.LCL"] * scale, fmt)
            put(f"rqOne{short}{t}Hi", row["asymp.UCL"] * scale, fmt)
    for o, short in (("empathy", "Emp"), ("helpfulness", "Help"), ("action_cov", "Act"),
                     ("appropriateness_latent", "Amount"), ("p_appropriate", "Appr")):
        for ct in ("P2 - P0", "P2 - P1"):
            row = c("RQ2", o, ct)
            put(f"rqTwo{short}{tag[ct]}", row.estimate)
            put(f"rqTwo{short}{tag[ct]}Lo", row["asymp.LCL"])
            put(f"rqTwo{short}{tag[ct]}Hi", row["asymp.UCL"])
            put(f"rqTwo{short}{tag[ct]}P", fmt_p(row.p_holm))
            for u in ("low", "medium", "high"):
                if o in ("p_appropriate", "helpfulness", "empathy"):
                    r2 = c("RQ2_by_urgency", o, ct, {"urgency": u})
                    put(f"rqTwo{short}{tag[ct]}{u.capitalize()}", r2.estimate)
                    put(f"rqTwo{short}{tag[ct]}{u.capitalize()}P", fmt_p(r2.p_holm))
    e = pd.read_csv(A / "emm_p_appropriate_policy_urgency.csv")
    for row in e.itertuples():
        put(f"apprProb{row.policy}{row.urgency.capitalize()}", 100 * row.prob, "{:.0f}")

    r3 = pd.read_csv(A / "rq3_agreement.csv")
